"""Convert the PNGs in icons/ into LVGL image headers in src/images/.

Source art is a dark drawing on a white or transparent background. Only its shape is
kept (LVGL A8 format): dark pixels become opaque, and the firmware tints them with the
gauge's color. Rerun this after changing a PNG. Requires Pillow.
"""

from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
MAX_WIDTH = 140   # pixels on the 480x480 display
MAX_HEIGHT = 120

ICONS = {  # PNG in icons/ -> C symbol and header name
    "Coolant.png": "icon_coolant",
    "Oil_Temp.png": "icon_oil_temp",
}


def convert(source: Path, name: str) -> None:
    art = Image.open(source).convert("RGBA")
    white = Image.new("RGBA", art.size, "white")
    mask = ImageOps.invert(Image.alpha_composite(white, art).convert("L"))
    # trim the margins so the drawing centers properly, ignoring near-white noise
    box = mask.point(lambda value: 255 if value > 8 else 0).getbbox()
    if box is None:
        raise SystemExit(f"{source.name} has no dark pixels to draw")
    mask = mask.crop(box)
    scale = min(MAX_WIDTH / mask.width, MAX_HEIGHT / mask.height)
    size = (round(mask.width * scale), round(mask.height * scale))
    mask = mask.resize(size, Image.LANCZOS)

    width, height = size
    pixels = mask.tobytes()
    rows = "\n".join(
        "  " + ",".join(f"0x{value:02x}" for value in pixels[start:start + width]) + ","
        for start in range(0, len(pixels), width)
    )

    header = ROOT / "src" / "images" / f"{name}.h"
    header.write_text(f"""// Generated by tools/convert_icons.py from icons/{source.name}. Do not edit.
#pragma once

#include <lvgl.h>

static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_map[] = {{
{rows}
}};

static const lv_image_dsc_t {name} = {{
  .header = {{
    .magic = LV_IMAGE_HEADER_MAGIC,
    .cf = LV_COLOR_FORMAT_A8,
    .flags = 0,
    .w = {width},
    .h = {height},
    .stride = {width},
  }},
  .data_size = sizeof({name}_map),
  .data = {name}_map,
}};
""", encoding="utf-8", newline="\n")
    print(f"{source.name} -> {header.relative_to(ROOT).as_posix()} ({width}x{height})")


if __name__ == "__main__":
    for filename, symbol in ICONS.items():
        convert(ROOT / "icons" / filename, symbol)
